"""A stand-in for PDAL's command line, for the tests that run where PDAL is not.

It answers the three commands 'pdal_cloud' gives -- 'info --schema', 'info
--summary' and 'pipeline' -- for clouds in a format of its own: JSON, one list
per dimension ({"X": [...], "Y": [...], ...}). A pipeline is applied as PDAL
documents its stages (crop by 'bounds', a 'range' on Classification, a
'decimation' by 'step') and written as the binary PLY 'writers.ply' writes,
names lowercased. What it was asked is appended to 'PC_FAKE_PDAL_LOG', so
that a test can say what PDAL would have been asked.

A cloud whose file name starts with 'broken' fails the way PDAL fails: a line
on standard error, and exit 1. Plain Python, so that it runs on any interpreter.
"""

import json
import os
import re
import struct
import sys

TYPES = {"float64": ("float64", "d"), "uint16": ("uint16", "H"), "uint8": ("uint8", "B")}


def log(entry):
    path = os.environ.get("PC_FAKE_PDAL_LOG")
    if path:
        with open(path, "a") as f:
            f.write(json.dumps(entry) + "\n")


def fail(message):
    sys.stderr.write("PDAL: %s\n" % message)
    sys.exit(1)


def load(source):
    if os.path.basename(source).startswith("broken"):
        fail("readers.las: Unable to open stream for '%s' with error 'No such file or directory'" % source)
    if "://" in source:
        source = os.environ.get("PC_FAKE_PDAL_REMOTE", "")
    with open(source) as f:
        return json.load(f)


def bounds(text):
    numbers = [float(v) for v in re.findall(r"-?[0-9.]+(?:e-?[0-9]+)?", text)]
    return numbers[0], numbers[1], numbers[2], numbers[3]  # xmin, xmax, ymin, ymax


def keep(cloud, chosen):
    return {name: [values[i] for i in chosen] for name, values in cloud.items()}


def run_pipeline(path):
    with open(path) as f:
        stages = json.load(f)["pipeline"]
    log({"pipeline": stages})
    reader = stages[0]
    cloud = load(reader["filename"])
    count = len(cloud["X"])
    if "bounds" in reader:
        xmin, xmax, ymin, ymax = bounds(reader["bounds"])
        cloud = keep(
            cloud, [i for i in range(count) if xmin <= cloud["X"][i] <= xmax and ymin <= cloud["Y"][i] <= ymax]
        )
    for stage in stages[1:]:
        count = len(cloud["X"])
        kind = stage["type"]
        if kind == "filters.crop":
            xmin, xmax, ymin, ymax = bounds(stage["bounds"])
            cloud = keep(
                cloud, [i for i in range(count) if xmin <= cloud["X"][i] <= xmax and ymin <= cloud["Y"][i] <= ymax]
            )
        elif kind == "filters.range":
            wanted = {int(v) for v in re.findall(r"Classification\[(\d+):\1\]", stage["limits"])}
            cloud = keep(cloud, [i for i in range(count) if int(cloud["Classification"][i]) in wanted])
        elif kind == "filters.decimation":
            cloud = keep(cloud, list(range(0, count, int(stage["step"]))))
        elif kind == "writers.ply":
            write(stage, cloud)
        else:
            fail("Couldn't create filter stage of type '%s'." % kind)


def write(stage, cloud):
    if stage.get("storage_mode") != "little endian":
        fail("the fake writes little endian only")
    specs = []
    for spec in stage["dims"].split(","):
        name, _, kind = spec.strip().partition("=")
        if name not in cloud:
            fail("writers.ply: Unknown dimension '%s' in provided dimension list." % name)
        specs.append((name, TYPES[kind]))
    count = len(cloud["X"])
    with open(stage["filename"], "wb") as f:
        header = ["ply", "format binary_little_endian 1.0", "comment Generated by PDAL", "element vertex %d" % count]
        header += ["property %s %s" % (kind[0], name.lower()) for name, kind in specs]
        f.write(("\n".join(header + ["end_header"]) + "\n").encode("ascii"))
        form = "<" + "".join(kind[1] for _, kind in specs)
        for i in range(count):
            values = []
            for name, kind in specs:
                value = cloud[name][i]
                values.append(float(value) if kind[1] == "d" else int(value))
            f.write(struct.pack(form, *values))


def info(arguments):
    driver = None
    if "--driver" in arguments:
        driver = arguments[arguments.index("--driver") + 1]
    source = arguments[-1]
    log({"info": [a for a in arguments if a.startswith("--")], "driver": driver, "source": source})
    cloud = load(source)
    if "--schema" in arguments:
        print(json.dumps({"schema": {"dimensions": [{"name": name, "size": 8} for name in cloud]}}))
    elif "--summary" in arguments:
        if os.environ.get("PC_FAKE_PDAL_NO_SUMMARY"):
            fail("No summary data available for '%s'." % source)
        print(json.dumps({"summary": {"num_points": len(cloud["X"])}}))


def main(arguments):
    if arguments[:1] == ["info"]:
        info(arguments[1:])
    elif arguments[:1] == ["pipeline"]:
        run_pipeline(arguments[1])
    else:
        fail("unknown command %r" % arguments)


if __name__ == "__main__":
    main(sys.argv[1:])
